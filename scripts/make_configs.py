"""Generate experiment configs and EXPERIMENT_REGISTRY.csv from one table, so the two cannot drift.

Hyperparameters marked UNTUNED are starting points to be fixed on the dev sets before the confirmatory runs.
"""
import csv, os, sys
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tier_ids import A as TIER_A, B as TIER_B, C as TIER_C  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEV = {"gsm8k_dev": "${PT_DATA}/eval_gsm8k_dev_1000.jsonl", "math_dev": "${PT_DATA}/eval_math_dev_500.jsonl"}
FINAL = {"gsm8k_test_final": "${PT_DATA}/eval_gsm8k_test_final.jsonl", "math_val_final": "${PT_DATA}/eval_math_val_final.jsonl"}
BASE = {"path": "${PT_MODEL:Qwen/Qwen2.5-Math-1.5B}", "revision": "4a83ca6e4526a4f2da3aa259ec36c259f66b2ab2", "expect_stage": "base"}
VLLM = {"name": "vllm", "device": "cuda:0", "gpu_mem": 0.8, "max_model_len": 2048, "prefix_caching": False}
COST = {"usd_per_hour": "${GPU_USD_PER_HOUR:}"}
rows = []


def w(path, cfg):
    p = os.path.join(ROOT, "configs", path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by scripts/make_configs.py - edit the generator, not this file\n")
        yaml.safe_dump(cfg, f, sort_keys=False)


def reg(eid, stage, tier, config, module, depends, hypothesis, primary, status="PLANNED", note="", evidence=""):
    rows.append(dict(experiment_id=eid, stage=stage, tier=tier, status=status, config="configs/" + config if config else "", module=module,
                     depends_on=depends, question=hypothesis, primary_metric=primary, evidence=evidence, notes=note))


def sft(name, data, seed, tier, dep, q, train=None, stage=2, primary="gsm8k_dev accuracy (final step)", note="", status="PLANNED", evidence=""):
    t = dict(lr=2e-5, betas=[0.9, 0.95], weight_decay=0.0, batch_size=32, micro_batch=4, token_budget=None, epochs=2, max_steps=None, warmup=4,
             max_grad_norm=1.0, append_eos=True, max_len=1536, log_entropy=True, save_every=25, grad_ckpt=False)
    t.update(train or {})
    cfg = dict(run_dir="${PT_RUNS}/sft/" + name, stage="sft", seed=seed, device="cuda:1", dtype="fp32", init=dict(BASE), engine=dict(VLLM),
               data=dict(path="${PT_DATA}/sft_all_labeled_4836.jsonl", subset=f"${{PT_DATA}}/subsets/{data}.json", prompt="r1_zero"),
               train=t, eval=dict(sets=DEV, max_tokens=1024, every=None, at_start=False, limit=None), cost=COST)
    w(f"sft/{name}.yaml", cfg)
    reg("SFT-" + name, stage, tier, f"sft/{name}.yaml", "posttrain.train_sft", dep, q, primary, status, note, evidence)


def grpo(name, init, tier, dep, q, seed=2026, g=None, t=None, status="PLANNED", stage=4, steps=100, folder="grpo", primary="gsm8k_dev accuracy (final step)", note="", ev=None, evidence=""):
    gg = dict(steps=steps, prompts_per_step=32, group_size=8, temperature=1.0, max_tokens=1024, loss="grpo_clip", clip=0.2, length_norm="const",
              norm_const=1024, std_norm=False, epochs=1, update_batch=256, group_filter="none", difficulty_sampling=False, sync_check_every=10,
              sync_tol=0.05, save_rollouts_every=10, check_rollout_logprobs=True, rollout_tol=0.05)  # sync_tol: diagnostic probe only, never stops a run
    gg.update(g or {})
    tt = dict(lr=5e-6, betas=[0.9, 0.95], weight_decay=0.0, micro_batch=4, token_budget=None, warmup=5, max_grad_norm=1.0, max_len=2064, save_every=20, grad_ckpt=False)
    tt.update(t or {})
    e = dict(sets=DEV, max_tokens=1024, every=25, at_start=True, limit=None)
    e.update(ev or {})
    cfg = dict(run_dir="${PT_RUNS}/" + folder + "/" + name, stage="grpo", seed=seed, device="cuda:1", dtype="fp32", init=init, engine=dict(VLLM),
               data=dict(path="${PT_DATA}/rl_train_pool.jsonl"), grpo=gg, train=tt, eval=e, cost=COST)
    w(f"{folder}/{name}.yaml", cfg)
    reg("GRPO-" + name, stage, tier, f"{folder}/{name}.yaml", "posttrain.train_grpo", dep, q, primary, status, note, evidence)


SFT512 = {"path": "${PT_RUNS}/sft/reverified_n512_s0/checkpoint", "expect_stage": "sft"}

# ---- Stage 1 ----
for nm, sets, tier, st, nt in (("dev", DEV, "mandatory", "DONE_PILOT", "run on the pilot pod"), ("final", FINAL, "mandatory", "GATED", "run once per pre-registered checkpoint; needs ALLOW_FINAL_EVAL=1")):
    w(f"eval/{nm}.yaml", dict(run_dir="${PT_RUNS}/eval/base_" + nm, seed=2026, init=dict(BASE) if nm == "dev" else {**BASE, "expect_stage": None}, engine=dict(VLLM),
                              prompts=["r1_zero", "question_only"], sets=sets, max_tokens=1024, limit=None, cost=COST))
    reg("EVAL-base-" + nm, 1 if nm == "dev" else 7, tier, f"eval/{nm}.yaml", "posttrain.evaluate", "PILOT-sync" if nm == "dev" else "design freeze",
        "zero-shot accuracy, format, length, failure categories", "accuracy; format rate", st, nt)
reg("EVAL-base-local-hf", 1, "mandatory", "", "", "", "base model on full GSM8K test with HF greedy (both prompts)", "accuracy; format rate", "DONE_LOCAL", "see results/stage0/base_eval")

# ---- pilots ----
sft("pilot_sft", "reverified_n128_s0", 0, "mandatory", "PILOT-sync", "does SFT run, fit, checkpoint, resume; seconds per step", dict(max_steps=6, save_every=3, micro_batch=8), stage=0,
    primary="step_s; peak GiB", note="pilot: never report accuracy; ran at micro_batch 8", status="DONE_PILOT", evidence="~/a5_pilot/sft/pilot_sft")
grpo("pilot_grpo_base", dict(BASE), "mandatory", "PILOT-sync", "correctness, memory, seconds per step, cost, zero-advantage rate", steps=10, folder="pilot", stage=0,
     primary="step_s; peak GiB; sync diff; informative rate", note="pilot: 2560 rollouts; never report accuracy", ev=dict(every=None, at_start=False, limit=100), t=dict(save_every=5),
     g=dict(check_rollout_logprobs=True, sync_check_every=1, save_rollouts_every=1), status="DONE_PILOT", evidence="~/a5_pilot/pilot/pilot_grpo_base (micro_batch 4; the first attempt at 8 is pilot_grpo_base_oom_mb8)")
reg("PILOT-sync", 0, "mandatory", "", "scripts/pilot_sync_check.py", "", "vLLM weights match PyTorch after sync; stale prefix-cache test", "mean |dlogprob| < 0.05", "DONE_PILOT", evidence="~/a5_pilot/pilot_sync.json, pilot_sync_cache.json")

# ---- Stage 2 ----
for lr in ("1e-5", "2e-5", "5e-5"):
    sft(f"tune_lr{lr}", "reverified_n512_s0", 100, "mandatory", "SFT-pilot_sft", "choose SFT lr on dev only; seed 100 is not used in confirmatory runs", dict(lr=float(lr)))
for arm in ("raw", "exact", "reverified"):
    for s in (0, 1, 2):
        sft(f"{arm}_n512_s{s}", f"{arm}_n512_s{s}", s, "mandatory", "SFT-tune_lr*", "matched 512: does label/verification source change accuracy?")
for s in (0, 1, 2):
    for nm, sub in (("exact_full", "exact_full"), ("reverified_full", "reverified_full"), ("reverified_sizecontrol", f"reverified_sizecontrol_s{s}")):
        sft(f"{nm}_s{s}", sub, s, "mandatory" if s == 0 else "recommended", "SFT-tune_lr*", "full: 3,420 exact vs 4,423 re-verified (after dedup/decontamination); size control separates volume from composition")
    for n in (128, 256, 1024, 2048):
        sft(f"reverified_n{n}_s{s}", f"reverified_n{n}_s{s}", s, "recommended", "SFT-tune_lr*", "sample efficiency curve (fixed epochs)")
    for n in (128, 2048):
        sft(f"exact_n{n}_s{s}", f"exact_n{n}_s{s}", s, "optional", "SFT-tune_lr*", "sample efficiency of exact-match data")

# ---- Stage 3 ----
w("ei/ei_base.yaml", dict(run_dir="${PT_RUNS}/ei/ei_base", stage="ei", seed=2026, device="cuda:1", dtype="fp32", init=dict(BASE), engine=dict(VLLM),
    data=dict(path="${PT_DATA}/rl_train_pool.jsonl"),
    ei=dict(iterations=3, problems_per_iter=1024, rollouts=4, temperature=1.0, max_tokens=1024, epochs_per_iter=1, max_per_problem=2, require_clean_format=True, min_accepted=64),
    train=dict(lr=2e-5, betas=[0.9, 0.95], weight_decay=0.0, batch_size=32, micro_batch=4, token_budget=None, warmup=4, max_grad_norm=1.0, append_eos=True, max_len=2064, log_entropy=True, grad_ckpt=False),
    eval=dict(sets=DEV, max_tokens=1024, limit=None), cost=COST))
reg("EI-base", 3, "mandatory", "ei/ei_base.yaml", "posttrain.train_ei", "SFT-tune_lr*", "does self-generated verified data improve over base?", "gsm8k_dev accuracy per iteration")

# ---- Stage 4 ----
for lr in ("2e-6", "5e-6", "1e-5"):
    grpo(f"tune_lr{lr}", dict(BASE), "recommended", "GRPO-pilot_grpo_base", "choose GRPO lr on dev only", seed=100, t=dict(lr=float(lr)), steps=30, ev=dict(every=None, at_start=False))
for s in (2026, 2027, 2028):
    tier = "mandatory" if s == 2026 else "recommended"
    grpo(f"A_base_s{s}", dict(BASE), tier, "GRPO-tune_lr*", "pathway A: Base -> GRPO", seed=s)
    grpo(f"B_sft512_s{s}", dict(SFT512), tier, "SFT-reverified_n512_s0; GRPO-tune_lr*", "pathway B: Base -> SFT -> GRPO; paired vs its own SFT parent", seed=s)

# ---- Stage 6 (gated on Stage 5 diagnostics) ----
G = "Stage 5 diagnostics"
grpo("X_filter_compute", dict(SFT512), "optional", G, "skip zero-advantage rollouts: same gradient, less update time", g=dict(group_filter="compute_only"), status="GATED", stage=6,
     primary="update_s at equal accuracy", note="run only if informative_rate < 0.6")
grpo("X_filter_renorm", dict(SFT512), "optional", G, "renormalise over informative rollouts; confounded with effective lr, needs an lr-matched control", g=dict(group_filter="renormalize"), status="GATED", stage=6)
grpo("X_difficulty", dict(SFT512), "optional", G, "p(1-p) prompt sampling raises informative rate per GPU-hour", g=dict(difficulty_sampling=True), status="GATED", stage=6,
     primary="accuracy per GPU-hour", note="run only if informative_rate < 0.6 and prompts are revisited")
grpo("X_offpolicy_e2", dict(SFT512), "optional", G, "reuse rollouts for 2 epochs, 4 updates/step", g=dict(epochs=2, update_batch=128), status="GATED", stage=6, note="compare with X_onpolicy_u4 at equal updates per step")
grpo("X_onpolicy_u4", dict(SFT512), "optional", G, "control: 4 smaller updates/step from twice the prompts, one epoch", g=dict(prompts_per_step=64, update_batch=128), status="GATED", stage=6)
grpo("X_lennorm_mean", dict(SFT512), "optional", G, "per-sequence mean vs constant length normalisation", g=dict(length_norm="mean"), status="GATED", stage=6, note="effective lr differs; tune lr for this arm")
grpo("X_stdnorm", dict(SFT512), "optional", G, "group std normalisation", g=dict(std_norm=True), status="GATED", stage=6, note="effective lr differs; tune lr for this arm")

# ---- historical runs on the research server (RESEARCH_SERVER_AUDIT.md). Never rerun, never counted as results of this pipeline. ----
H = "historical; recipe recovered (RESEARCH_SERVER_AUDIT.md); not this pipeline: pure bf16, summed loss, no end token, in-loop checks on GSM8K test"
reg("HIST-SFT128", 2, "reference", "", "", "", "earlier SFT on 128 filtered traces (first of two runs)", "GSM8K test 1062/1319 (recounted)", "HISTORICAL", H + "; the evaluated checkpoint was overwritten by a second run", "~/a5_bundle: debug_comparison/sft_128_full_results.jsonl; results/recovered_audit/")
reg("HIST-SFT512", 2, "reference", "", "", "", "earlier SFT on 512 filtered traces", "GSM8K test 1060/1319 (recounted)", "HISTORICAL", H, "~/a5_recovered/sft512_evaluation.jsonl; results/recovered_audit/")
reg("HIST-GRPO512", 4, "reference", "", "", "HIST-SFT512 (verified parent path)", "earlier short GRPO run, checkpoint called best", "GSM8K test 1069/1319 (recounted)", "HISTORICAL",
    H + "; 'best' = step 4 of 10, selected on the first 128 GSM8K TEST questions", "~/a5_recovered/grpo_evaluation.jsonl; results/recovered_audit/")
for nm, env in (("sft512", "HIST_SFT512"), ("grpo512", "HIST_GRPO512")):
    w(f"eval/hist_{nm}_dev.yaml", dict(run_dir="${PT_RUNS}/eval/hist_" + nm + "_dev", seed=2026, engine=dict(VLLM), prompts=["r1_zero"], sets=DEV, max_tokens=1024, limit=None, cost=COST,
      init=dict(path="${%s_PATH:unset}" % env, revision=None, expect_sha256="${%s_SHA256:}" % env, declared_stage="historical", expect_stage="historical")))
    reg(f"HIST-EVAL-{nm}-dev", 2, "reference", f"eval/hist_{nm}_dev.yaml", "posttrain.evaluate", "server audit report; authorization",
        "score the historical checkpoint on dev questions that were not part of its recorded evaluations (inference only)", "gsm8k_dev accuracy; paired sft512 vs grpo512", "DEFERRED",
        "not worth GPU time: n=1000 cannot resolve a 0.7 pp difference. Use gsm8k_dev only: the GRPO training pool contains all 500 math_dev problems")

# ---- plan status ----
NOTE = dict(HOLD_B="hold until Tier A is reviewed", DEFERRED="Tier C: not scheduled")
for r in rows:
    r["plan"] = "A" if r["experiment_id"] in TIER_A else "B" if r["experiment_id"] in TIER_B else "C" if r["experiment_id"] in TIER_C else ""
    if r["plan"] == "C" or (r["plan"] == "B" and r["status"] == "PLANNED"):
        r["status"] = "DEFERRED" if r["plan"] == "C" else "HOLD_B"
        r["notes"] = "; ".join(x for x in (r["notes"], NOTE[r["status"]]) if x)
    if r["experiment_id"].startswith("SFT-raw_n512"):
        r["notes"] += "; 479-486 of the 512 raw samples are already verified-correct, so contrast with the other arms is small"
    if r["experiment_id"] == "SFT-exact_n512_s0":
        r["notes"] = "closest match to HIST-SFT512, still needed: it must share data rules, recipe, code and dev protocol with reverified_n512_s0"
    if r["experiment_id"] == "GRPO-B_sft512_s2026":
        r["notes"] = "closest match to HIST-GRPO512, still needed: parent, steps, selection rule and dev protocol differ or are unknown"

with open(os.path.join(ROOT, "EXPERIMENT_REGISTRY.csv"), "w", encoding="utf-8", newline="") as f:
    wr = csv.DictWriter(f, fieldnames=list(rows[0]))
    wr.writeheader()
    wr.writerows(rows)
print(len(rows), "experiments;", {t: sum(r["tier"] == t for r in rows) for t in ("mandatory", "recommended", "optional")})
